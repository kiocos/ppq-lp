import { chromium } from 'playwright';
import sharp from 'sharp';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 }, userAgent: 'Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130 Safari/537.36' });
const p = await ctx.newPage();
await p.goto('https://fontsinuse.com/search?terms=geist', { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(1500);
const tf = await p.evaluate(() => [...document.querySelectorAll('a[href*="/typefaces/"]')].map(a => a.href + ' | ' + a.innerText.trim()).filter(x => /geist/i.test(x)));
console.log(tf.join('\n'));
const geist = 'https://fontsinuse.com/typefaces/237493/geist-sans';
console.log('GEIST URL', geist);
await p.goto(geist, { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(2500);
const pairs = await p.evaluate(() => document.body.innerText.match(/(Fonts?|Typefaces?)[\s\S]{0,40}/g)?.slice(0, 5));
await p.screenshot({ path: '../research/fiu-geist.png', fullPage: true });
const m = await sharp('../research/fiu-geist.png').metadata();
await sharp('../research/fiu-geist.png').extract({ left: 0, top: 0, width: 1440, height: Math.min(m.height, 3200) }).resize({ width: 900 }).toFile('../research/fiu-geist-s.png');
await p.goto('https://fontsinuse.com/in/1/topics/32/technology', { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(2500);
await p.screenshot({ path: '../research/fiu-tech.png', fullPage: true });
const m2 = await sharp('../research/fiu-tech.png').metadata();
await sharp('../research/fiu-tech.png').extract({ left: 0, top: 0, width: 1440, height: Math.min(m2.height, 3200) }).resize({ width: 900 }).toFile('../research/fiu-tech-s.png');
await b.close();
